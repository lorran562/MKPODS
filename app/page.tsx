'use client';

import { useMemo, useState } from 'react';
import Navbar from '@/components/Navbar';
import ProductGrid from '@/components/ProductGrid';
import { useStore } from '@/lib/store';

export default function Home() {
  const { products, isLoaded } = useStore();
  const [searchTerm, setSearchTerm] = useState('');

  const filteredProducts = useMemo(() => {
    const term = searchTerm.trim().toLowerCase();
    if (!term) return products;
    return products.filter((product) =>
      product.model.toLowerCase().includes(term) ||
      product.brand.toLowerCase().includes(term) ||
      product.flavors.some((flavor) => flavor.name.toLowerCase().includes(term))
    );
  }, [products, searchTerm]);

  if (!isLoaded) {
    return <div className="flex min-h-screen items-center justify-center bg-[#080a0a]"><div className="h-9 w-9 animate-spin rounded-full border-2 border-emerald-400/20 border-t-emerald-400" /></div>;
  }

  return (
    <main id="top" className="min-h-screen bg-[#080a0a] text-zinc-100">
      <Navbar onSearch={setSearchTerm} />
      <section className="border-b border-white/[.07] bg-[#0b0f0e] pb-6 pt-24 sm:pb-8 sm:pt-28">
        <div className="container mx-auto px-4 sm:px-6 md:px-8">
          <div className="flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
            <div>
              <p className="mb-2 text-[10px] font-black uppercase tracking-[.2em] text-emerald-400">77SMOKE · catálogo</p>
              <h1 className="font-display text-3xl font-bold tracking-[-.06em] text-white sm:text-5xl">Escolha seu produto</h1>
              <p className="mt-2 text-sm text-zinc-400">Selecione o modelo, escolha o sabor e envie seu pedido pelo WhatsApp.</p>
            </div>
            <a href="#catalogo" className="inline-flex min-h-11 items-center justify-center rounded-full bg-emerald-400 px-5 text-sm font-bold text-[#07100b] transition hover:bg-emerald-300">Ver catálogo</a>
          </div>
        </div>
      </section>

      <section id="catalogo" className="py-8 sm:py-12">
        <div className="container mx-auto px-4 sm:px-6 md:px-8">
          <div className="mb-6 grid gap-3 rounded-2xl border border-emerald-400/20 bg-emerald-400/[.06] p-4 sm:grid-cols-2 sm:items-center sm:p-5">
            <div><p className="text-xs font-black uppercase tracking-[.16em] text-emerald-300">Atacado acima de 10 peças</p><p className="mt-1 text-xs text-zinc-400">Valores por unidade · pronta entrega</p></div>
            <p className="text-xs font-bold text-red-300 sm:text-right">🚨 Itens com alerta estão na promoção</p>
          </div>
          {filteredProducts.length > 0 ? <ProductGrid products={filteredProducts} /> : (
            <div className="rounded-2xl border border-white/10 bg-white/[.03] py-20 text-center">
              <p className="text-sm text-zinc-400">Nenhum produto encontrado para “{searchTerm}”.</p>
              <button onClick={() => setSearchTerm('')} className="mt-3 text-sm font-bold text-emerald-400 hover:text-emerald-300">Limpar busca</button>
            </div>
          )}
        </div>
      </section>

      <footer className="border-t border-white/[.07] py-6">
        <div className="container mx-auto flex flex-col gap-2 px-4 text-center text-[11px] text-zinc-600 sm:flex-row sm:justify-between sm:px-6 sm:text-left md:px-8">
          <span>77SMOKE · pedidos pelo WhatsApp</span>
          <span>Venda proibida para menores de 18 anos.</span>
        </div>
      </footer>
    </main>
  );
}





















































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































